// pages/player/detail.js - 球员创建/编辑
const pinyin = require('../../utils/pinyin.js')

const DOCUMENT_TYPES = [
  { value: 'resident_id', label: '居民身份证' },
  { value: 'passport', label: '护照' }
]

function inferDocumentType(row = {}) {
  if (row.documentType === 'passport' || row.documentType === 'resident_id') return row.documentType
  const identity = String(row.idCard || row.identityNumber || '').trim().toUpperCase()
  if (/^\d{17}[\dX]$/.test(identity)) return 'resident_id'
  if (/^(?=.*[A-Z])[A-Z0-9]{5,12}$/.test(identity) || (/^[A-Z0-9]{5,12}$/.test(identity) && !/^\d+$/.test(identity))) return 'passport'
  return 'resident_id'
}

function ageFromBirthDate(birthDate) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(birthDate || ''))) return ''
  const [y, m, d] = String(birthDate).split('-').map(Number)
  const today = new Date()
  let age = today.getFullYear() - y
  if (today.getMonth() + 1 < m || (today.getMonth() + 1 === m && today.getDate() < d)) age -= 1
  return age >= 0 ? String(age) : ''
}

Page({

  data: {
    teamId: '',
    playerId: null,
    isEdit: false,
    role: '',
    // 表单字段
    name: '',
    jerseyName: '',
    jerseyNumber: '',
    position: '',
    isCaptain: false,
    age: '',
    birthDate: '',
    idCard: '',
    documentType: 'resident_id',
    documentTypeIndex: 0,
    documentTypeLabel: '居民身份证',
    documentTypeLabels: DOCUMENT_TYPES.map(item => item.label),
    idCardLabel: '身份证号',
    idCardPlaceholder: '请输入18位身份证号',
    idCardMaxlength: 18,
    isPassport: false,
    showIdCardAutoHint: true,
    showAutoBirthDate: false,
    showAutoAge: false,
    birthDateDisplay: '请选择出生日期',
    phone: '',
    remark: '',
    photo: '',
    nationality: '中国',
    height: '',
    weight: '',
    province: '',
    city: '',
    district: '',
    // 位置选项
    positions: ['守门员', '后卫', '前卫', '前锋'],
    // 国籍选项：与球员卡国旗目录同源；首项「待确认」对应地球图标
    nationalities: ['待确认'].concat(require('../../utils/nationality.js').labels())
  },

  onLoad(options) {
    this.setData({
      teamId: options.teamId
    })
    if (options.playerId) {
      this.setData({ playerId: options.playerId, isEdit: true })
      this.loadPlayer(options.playerId)
    } else {
      this.applyDocumentTypeUI('resident_id')
    }
  },

  applyDocumentTypeUI(documentType, extra = {}) {
    const isPassport = documentType === 'passport'
    const birthDate = extra.birthDate != null ? extra.birthDate : this.data.birthDate
    const age = extra.age != null ? extra.age : this.data.age
    const index = DOCUMENT_TYPES.findIndex(item => item.value === documentType)
    const safeIndex = index >= 0 ? index : 0
    this.setData({
      documentType,
      documentTypeIndex: safeIndex,
      documentTypeLabel: DOCUMENT_TYPES[safeIndex].label,
      idCardLabel: isPassport ? '护照号' : '身份证号',
      idCardPlaceholder: isPassport ? '请输入护照号' : '请输入18位身份证号',
      idCardMaxlength: isPassport ? 12 : 18,
      isPassport,
      showIdCardAutoHint: !isPassport,
      showAutoBirthDate: !isPassport && !!birthDate,
      showAutoAge: !isPassport && !!age,
      birthDateDisplay: birthDate || '请选择出生日期',
      ...extra
    })
  },

  // 加载球员信息
  async loadPlayer(playerId) {
    try {
      const db = wx.cloud.database()
      const res = await db.collection('players').doc(playerId).get()
      const documentType = inferDocumentType(res.data || {})
      const birthDate = res.data.birthDate || ''
      const age = res.data.age ? String(res.data.age) : ageFromBirthDate(birthDate)
      this.setData({
        name: res.data.name || '',
        jerseyName: res.data.jerseyName || '',
        jerseyNumber: String(res.data.jerseyNumber || ''),
        position: res.data.position || '',
        isCaptain: res.data.isCaptain || false,
        age,
        birthDate,
        idCard: res.data.idCard || res.data.identityNumber || '',
        phone: res.data.phone || '',
        remark: res.data.remark || '',
        photo: res.data.photo || '',
        nationality: res.data.nationality == null ? '' : String(res.data.nationality),
        height: res.data.height || '',
        weight: res.data.weight || '',
        province: res.data.province || '',
        city: res.data.city || '',
        district: res.data.district || ''
      })
      this.applyDocumentTypeUI(documentType, { birthDate, age })
    } catch (err) {
      console.error('加载球员失败:', err)
      wx.showToast({ title: '加载失败', icon: 'none' })
    }
  },
  onNameInput(e) {
    const name = e.detail.value
    let jerseyName = this.data.jerseyName
    if (name.length >= 2 && (!jerseyName || this.data._autoGenerated)) {
      jerseyName = pinyin.generateJerseyName(name)
      this.setData({ _autoGenerated: true })
    }
    this.setData({ name, jerseyName })
  },

  onJerseyNameInput(e) {
    this.setData({ jerseyName: e.detail.value, _autoGenerated: false })
  },

  onDocumentTypeChange(e) {
    const index = Number(e.detail.value || 0)
    const selected = DOCUMENT_TYPES[index] || DOCUMENT_TYPES[0]
    const patch = {}
    if (selected.value === 'passport' && this.data.nationality === '中国') {
      patch.nationality = ''
    }
    if (selected.value === 'resident_id' && !this.data.nationality) {
      patch.nationality = '中国'
    }
    this.applyDocumentTypeUI(selected.value, patch)
    if (selected.value === 'resident_id' && this.data.idCard) {
      this.onIdCardInput({ detail: { value: this.data.idCard } })
    }
  },

  // 身份证号 → 自动提取年龄和出生日期；护照仅规范化号码
  onIdCardInput(e) {
    let idCard = String(e.detail.value || '')
    if (this.data.documentType === 'passport') {
      idCard = idCard.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 12)
      this.setData({ idCard })
      return
    }
    const parsed = pinyin.parseIdCard(idCard)
    if (parsed) {
      this.applyDocumentTypeUI('resident_id', {
        idCard,
        birthDate: parsed.birthDate,
        age: String(parsed.age)
      })
    } else {
      this.applyDocumentTypeUI('resident_id', {
        idCard,
        birthDate: '',
        age: ''
      })
    }
  },

  // 上传球员照片（自动压缩）
  choosePhoto() {
    wx.chooseMedia({
      count: 1,
      mediaType: ['image'],
      success: (res) => {
        const tempPath = res.tempFiles[0].tempFilePath
        this.uploadPhoto(tempPath)
      }
    })
  },

  async uploadPhoto(filePath) {
    wx.showLoading({ title: '上传中...' })
    try {
      // 先压缩图片
      const compressRes = await new Promise((resolve, reject) => {
        wx.compressImage({
          src: filePath,
          quality: 80,
          success: resolve,
          fail: () => resolve({ tempFilePath: filePath })
        })
      })

      const compressedPath = compressRes.tempFilePath || filePath
      const ext = (compressedPath.split('.').pop() || 'jpg').toLowerCase()
      const cloudPath = `player-photos/${Date.now()}-${Math.random().toString(36).substr(2, 8)}.${ext}`
      const res = await wx.cloud.uploadFile({ cloudPath, filePath: compressedPath })

      this.setData({ photo: res.fileID })
      wx.showToast({ title: '上传成功', icon: 'success' })
    } catch (err) {
      console.error('上传失败:', err)
      wx.showToast({ title: '上传失败', icon: 'none' })
    }
    wx.hideLoading()
  },

  onBirthDateChange(e) {
    const birthDate = e.detail.value
    const age = ageFromBirthDate(birthDate)
    this.applyDocumentTypeUI(this.data.documentType, { birthDate, age })
  },
  onAgeInput(e) { this.setData({ age: e.detail.value }) },
  onJerseyInput(e) { this.setData({ jerseyNumber: e.detail.value }) },
  onPhoneInput(e) { this.setData({ phone: e.detail.value }) },
  onRemarkInput(e) { this.setData({ remark: e.detail.value }) },
  selectPosition(e) { this.setData({ position: e.currentTarget.dataset.pos }) },
  toggleCaptain() { this.setData({ isCaptain: !this.data.isCaptain }) },
  onNationalityChange(e) {
    const picked = this.data.nationalities[e.detail.value] || '待确认'
    this.setData({ nationality: picked === '待确认' ? '' : picked })
  },
  onHeightInput(e) { this.setData({ height: e.detail.value }) },
  onWeightInput(e) { this.setData({ weight: e.detail.value }) },
  onProvinceInput(e) { this.setData({ province: e.detail.value }) },
  onCityInput(e) { this.setData({ city: e.detail.value }) },
  onDistrictInput(e) { this.setData({ district: e.detail.value }) },

  // 保存球员
  async savePlayer() {
    const { name, idCard, documentType } = this.data
    if (!name.trim()) {
      wx.showToast({ title: '请输入球员姓名', icon: 'none' })
      return
    }
    const identity = String(idCard || '').trim().toUpperCase()
    if (documentType === 'passport') {
      if (!/^[A-Z0-9]{5,12}$/.test(identity)) {
        wx.showToast({ title: '请填写有效护照号', icon: 'none' })
        return
      }
      if (!/^\d{4}-\d{2}-\d{2}$/.test(String(this.data.birthDate || ''))) {
        wx.showToast({ title: '护照请填写出生日期', icon: 'none' })
        return
      }
      if (!String(this.data.nationality || '').trim()) {
        wx.showToast({ title: '护照请选择国籍', icon: 'none' })
        return
      }
    } else if (identity && !/^\d{17}[\dX]$/.test(identity)) {
      wx.showToast({ title: '请输入18位身份证号', icon: 'none' })
      return
    }

    wx.showLoading({ title: '保存中...' })

    try {
      const db = wx.cloud.database()
      const playerData = {
        name: this.data.name.trim(),
        jerseyName: this.data.jerseyName.trim(),
        jerseyNumber: parseInt(this.data.jerseyNumber) || 0,
        position: this.data.position,
        isCaptain: this.data.isCaptain,
        age: this.data.age ? parseInt(this.data.age) : 0,
        birthDate: this.data.birthDate,
        idCard: identity,
        documentType: documentType || 'resident_id',
        phone: this.data.phone,
        remark: this.data.remark,
        photo: this.data.photo,
        teamId: this.data.teamId,
        nationality: String(this.data.nationality || '').trim(),
        height: this.data.height,
        weight: this.data.weight,
        province: this.data.province,
        city: this.data.city,
        district: this.data.district,
        nativePlace: [this.data.province, this.data.city, this.data.district].filter(Boolean).join(''),
        updateTime: db.serverDate()
      }

      if (this.data.isEdit) {
        await db.collection('players').doc(this.data.playerId).update({ data: playerData })
      } else {
        playerData.createTime = db.serverDate()
        playerData.isCreatedByCoach = true
        playerData.isBound = false
        await db.collection('players').add({ data: playerData })
        try {
          const res = await db.collection('teams').doc(this.data.teamId).get()
          await db.collection('teams').doc(this.data.teamId).update({
            data: { playerCount: (res.data.playerCount || 0) + 1 }
          })
        } catch (err) {}
      }

      wx.showToast({ title: '保存成功', icon: 'success' })
      setTimeout(() => wx.navigateBack(), 1500)
    } catch (err) {
      console.error('保存失败:', err)
      wx.showToast({ title: '保存失败', icon: 'none' })
    }
    wx.hideLoading()
  }
})
