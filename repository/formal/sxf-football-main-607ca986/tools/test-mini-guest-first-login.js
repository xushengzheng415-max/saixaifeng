const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const read = relativePath => fs.readFileSync(path.join(root, relativePath), 'utf8')

const appConfig = JSON.parse(read('miniprogram/app.json'))
const appSource = read('miniprogram/app.js')
const homeTemplate = read('miniprogram/pages/home/home.wxml')
const homeSource = read('miniprogram/pages/home/home.js')
const loginTemplate = read('miniprogram/pages/login/login.wxml')

assert.strictEqual(appConfig.pages[0], 'pages/login/login', '首次打开必须进入带免登录小房子的登录页')
assert.match(loginTemplate, /class="guest-home"[\s\S]*bindtap="goToGuestHome"/, '登录页左上角必须保留免登录小房子入口')
assert.match(loginTemplate, /\/images\/icons\/home-entry-white\.svg/, '免登录入口必须使用清晰的房屋图标')
assert.match(read('miniprogram/pages/login/login.js'), /goToGuestHome:[\s\S]*wx\.switchTab\(\{ url: '\/pages\/home\/home' \}\)/, '小房子必须直接进入首页')
assert.doesNotMatch(appSource, /routeGuestHomeLaunchToLogin|reLaunch\s*\(\s*\{\s*url:\s*['"]\/pages\/login\/login/, '进入游客首页后不得被全局逻辑强制弹回登录页')
assert.match(homeTemplate, /当前未登录/, '游客首页必须明确显示当前未登录')
assert.match(homeTemplate, /免登录浏览公开赛事/, '游客首页必须提供真实的免登录浏览入口')
assert.match(homeTemplate, /浏览后，可自行选择登录/, '游客首页必须明确由用户主动选择登录')
assert.doesNotMatch(homeTemplate, /login-hero|guest-title|游客首页/, '小房子进入后不得显示独立游客介绍页')
assert.match(homeTemplate, /guest-public-card[\s\S]*guest-service-grid/, '未登录状态必须呈现首页功能内容')
assert.match(homeTemplate, /首页功能演示[\s\S]*示例数据 · 不保存/, '未登录首页必须提供明确标注的演示状态')
assert.match(homeTemplate, /guestDemoMetrics[\s\S]*guestDemoTasks/, '演示首页必须展示概览和任务内容')
assert.match(homeSource, /openGuestDemoAction:[\s\S]*示例数据，不会保存或产生业务记录/, '演示交互不得冒充真实业务数据')
assert.match(homeSource, /isDevtools\(\)[\s\S]*options\.reviewGuest === '1'[\s\S]*isLoggedIn: false/, '开发者工具必须能固定验证未登录首页演示')
assert.match(homeSource, /goToLogin:[\s\S]*wx\.navigateTo/, '登录页只能由首页用户动作打开')
assert.doesNotMatch(homeTemplate, /getPhoneNumber|chooseAvatar/, '游客首页不得请求手机号、头像或昵称授权')
assert.match(loginTemplate, /open-type="getPhoneNumber"/, '正式登录继续使用手机号唯一凭证')
assert.doesNotMatch(loginTemplate, /chooseAvatar|type="nickname"|getUserProfile/, '登录不得捆绑索取头像或昵称')

console.log('小程序小房子进入首页演示测试通过：18/18')
