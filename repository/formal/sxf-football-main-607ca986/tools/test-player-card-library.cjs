const assert = require('node:assert/strict')
const {db,cloud,table,files,image} = require('./test-player-card-preload.cjs')
const {createPlayerCardTemplates} = require('../cloudfunctions/webLoginApi/playerCardTemplates.cjs')
const {createPlayerCards} = require('../cloudfunctions/webLoginApi/playerCards.cjs')
const {libraryId} = require('../cloudfunctions/webLoginApi/playerCardLibrary.cjs')
const score = {status:'ready',tier:'bronze',points:0,metrics:{appearances:0},canChangeBackground:false,canReplacePhoto:false,scoreVersion:'test/1'}
const publish = createPlayerCardTemplates({cloud,scoreForPlayer:async()=>score,authenticateWebSession:async()=>({success:true,principalType:'platform_owner',user:{isPlatformOwner:true},userId:'owner'})})
const h5 = createPlayerCards({cloud,readBaseCard:async p=>({status:p.playerCardFileId?'ready':'unavailable',fileId:p.playerCardFileId,url:p.playerCardFileId?'https://test.local/'+p.playerCardFileId:'',templateVersion:1,cardDataVersion:p.playerCardVersion,renderVersion:'resvg/1'}),scoreForPlayer:async()=>score,hashSessionToken:value=>value,dateValue:value=>Number(value)})
const pc = (action,data={}) => publish({action,...data})
const api = (action,data={}) => h5({action,fanSessionToken:'session1',...data})
async function main() {
  files.set('cloud://base',Buffer.from(image(false).split(',')[1],'base64'))
  files.set('cloud://portrait',Buffer.from(image(false).split(',')[1],'base64'))
  table('teams').set('team1',{_id:'team1',name:'甲队'});table('teams').set('team2',{_id:'team2',name:'乙队'})
  table('tournaments').set('event1',{_id:'event1',name:'专属测试赛'})
  table('players').set('p1',{_id:'p1',name:'已绑定球员',teamId:'team1',linkedUserId:'u1',recentPortraitId:'portrait1',playerCardFileId:'cloud://base',playerCardVersion:7,playerCardTier:'bronze',playerCardPoints:0})
  table('players').set('p2',{_id:'p2',name:'其他球员',teamId:'team2',linkedUserId:'u2',playerCardFileId:'cloud://other-base',playerCardVersion:9,playerCardTier:'bronze'})
  table('fan_h5_sessions').set('s1',{_id:'s1',tokenHash:'session1',active:true,expiresAt:Date.now()+60000,serviceAccountOpenId:'openid1'})
  table('parent_profile_submissions').set('sub1',{_id:'sub1',serviceAccountOpenId:'openid1',status:'submitted',playerId:'p1',registrantType:'self',registrantUserId:'u1',parentInvite:'invite1'})
  table('parent_portraits').set('portrait1',{_id:'portrait1',status:'confirmed',parentInvite:'invite1',transparentFileId:'cloud://portrait'})
  table('roster_snapshots').set('r1',{_id:'r1',tournamentId:'event1',teamId:'team1',status:'approved',version:1,playerIds:['p1']})
  const baseBefore = structuredClone(table('players').get('p1')), ids=[]
  const scopes = [{type:'platform'},{type:'team',targetId:'team1'},{type:'team',targetId:'team1'}, {type:'tournament',targetId:'event1'},{type:'player',targetId:'p1'}, {type:'team',targetId:'team2'}, {type:'tournament',targetId:'event1'}]
  for(let i=0;i<scopes.length;i++) {
    const saved = await pc('savePlayerCardTemplate',{title:'预装卡'+i,tier:i===6?'gold':'bronze',preload:scopes[i],backgroundData:image(false),maskData:image(true)})
    assert.equal(saved.success,true,saved.error);ids.push(saved.templateId)
    const result=await pc('publishPlayerCardTemplate',{templateId:saved.templateId,revision:1})
    assert.equal(result.status,'active',result.error)
    assert.equal(result.affected,0,'initial preload creates catalog entries, never updates base files')
  }
  let listed=await api('listMyPlayerCards')
  assert.equal(listed.players.length,1)
  assert.equal(listed.players[0].cardUrl,'https://test.local/cloud://base')
  assert.equal(listed.players[0].preloadedCards.length,6)
  assert(!listed.players[0].preloadedCards.some(card=>card.templateId===ids[5]),'other team template cannot be granted')
  assert.equal(listed.players[0].preloadedCards.find(card=>card.templateId===ids[6]).status,'locked')
  assert.deepEqual(table('players').get('p1'),baseBefore,'adding cards must not modify player base card, points or display')
  const templateId=ids[1], detail=await api('getMyPreloadedPlayerCard',{playerId:'p1',templateId})
  assert.equal(detail.success,true,detail.error);assert.equal(detail.card.preload.targetName,'甲队')
  const input={playerId:'p1',templateId,templateVersion:detail.card.templateVersion,crop:{zoom:1.1,x:0.1,y:0},expectedRevision:0}
  const preview=(await api('previewMyPreloadedPlayerCard',input)).imageData
  assert(preview.startsWith('data:image/png;base64,'))
  assert.equal((await api('saveMyPreloadedPlayerCard',input)).success,true)
  assert.deepEqual(files.get(table('player_card_library').get(libraryId('p1',templateId)).fileId),Buffer.from(preview.split(',')[1],'base64'),'H5 preview and saved PNG are identical')
  assert.deepEqual(table('players').get('p1'),baseBefore,'saving added card preserves original file and grade')
  assert.equal((await api('saveMyPreloadedPlayerCard',input)).code,'PLAYER_CARD_LIBRARY_CONFLICT')
  assert.equal((await api('getMyPreloadedPlayerCard',{playerId:'p2',templateId})).code,'PLAYER_CARD_FORBIDDEN')
  assert.equal((await api('getMyPreloadedPlayerCard',{playerId:'p1',templateId:ids[5]})).code,'PLAYER_CARD_LIBRARY_FORBIDDEN')
  assert.equal((await api('getMyPreloadedPlayerCard',{playerId:'p1',templateId:ids[6]})).code,'PLAYER_CARD_LIBRARY_LOCKED')
  const selected=await api('selectMyPlayerCard',{playerId:'p1',templateId})
  assert.equal(selected.success,true,selected.error)
  assert.equal(table('players').get('p1').playerCardDisplayTemplateId,templateId)
  assert.equal(table('players').get('p1').playerCardFileId,'cloud://base')
  listed=await api('listMyPlayerCards');assert.equal(listed.players[0].displayState,'ready')
  assert(listed.players[0].displayCardUrl);assert.equal(listed.players[0].cardUrl,'https://test.local/cloud://base')
  const beforeOther=structuredClone(table('players').get('p2'))
  const grantBefore=structuredClone(table('player_card_library').get(libraryId('p1',templateId)))
  const saved=await pc('savePlayerCardTemplate',{templateId,revision:2,title:'甲队预装卡新版',tier:'bronze'})
  assert.equal(saved.success,true,saved.error)
  let result=await pc('publishPlayerCardTemplate',{templateId,revision:3})
  assert.equal(result.status,'pending');assert.equal(result.total,1,'only generated variants of this template update')
  result=await pc('continuePlayerCardTemplatePublish',{jobId:result.jobId})
  assert.equal(result.status,'active',result.error)
  assert.equal(result.affected,1)
  assert.equal(table('players').get('p1').playerCardFileId,'cloud://base');assert.deepEqual(table('players').get('p2'),beforeOther)
  assert.equal(table('player_card_library').get(libraryId('p1',templateId)).fileId,grantBefore.fileId,'original variant is preserved for audit')
  listed=await api('listMyPlayerCards');assert.equal(listed.players[0].preloadedCards.length,6)
  assert.equal(listed.players[0].preloadedCards.find(card=>card.templateId===templateId).templateVersion,2)
  assert.equal(listed.players[0].preloadedCards.find(card=>card.templateId===templateId).status,'ready')
  assert.equal((await api('selectMyPlayerCard',{playerId:'p1',templateId:''})).success,true)
  assert.equal(table('players').get('p1').playerCardDisplayTemplateId,'')
  assert.equal(table('players').get('p1').playerCardFileId,'cloud://base')
  table('players').get('p1').teamId='team2'
  listed=await api('listMyPlayerCards');assert(listed.players[0].preloadedCards.some(card=>card.templateId===templateId),'previously added cards are not silently removed on team changes')
  table('players').get('p1').linkedUserId='new-owner'
  assert.equal((await api('listMyPlayerCards')).players.length,0,'current binding is required')
  console.log('PASS: additive H5 library, exact scope eligibility, multiple same-scope cards, independent save/display, grades/auth, retained base, scoped updates and ownership changes')
}
main().catch(error=>{console.error(error);process.exitCode=1})
