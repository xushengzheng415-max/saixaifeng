const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const api = require('../cloudfunctions/dataCenter/shared/match-score.cjs')
const match = {homeTeamId:'home-id',awayTeamId:'away-id',homeTeamName:'主队名称',awayTeamName:'客队名称',homeScore:1,awayScore:1,resolution:'penalties',homePenaltyScore:4,awayPenaltyScore:3,winnerTeamId:'home-id'}
assert.deepEqual([api.decision(match).home,api.decision(match).away,api.decision(match).winnerSide],[4,3,'home'])
assert.equal(api.scoreText(match),'1 : 1（点球 4 : 3 · 主队胜）')
assert.equal(api.decision({...match,homePenaltyScore:3,awayPenaltyScore:4,winnerTeamId:'away-id'}).winnerName,'客队名称')
assert.equal(api.decision({homeScore:1,awayScore:1}).isShootout,false)
assert.equal(api.decision({homeScore:1,awayScore:1,homePenaltyScore:0,awayPenaltyScore:0}).isShootout,false)
assert.equal(api.decision({...match,resolution:'penalty_shootout'}).isShootout,true)
assert.equal(api.decision({...match,resolution:'',decisionMethod:'shootout'}).isShootout,true)
assert.equal(api.decision({...match,homePenaltyScore:null,awayPenaltyScore:null}).home,null)
assert.match(api.decision({...match,homePenaltyScore:null,awayPenaltyScore:null}).label,/待补录/)
const conflict = api.publicFields({...match,winnerTeamId:'away-id'})
assert.equal(api.decision({...conflict,homeScore:1,awayScore:1}).winnerSide,'')
assert.match(api.decision(conflict).label,/待核对/)
const publicMatch = {...api.publicFields(match),homeName:match.homeTeamName,awayName:match.awayTeamName,homeScore:1,awayScore:1}
assert.equal(api.decision(publicMatch).label,api.decision(match).label)
assert.equal(api.decision(publicMatch).winnerName,match.homeTeamName)
const sandbox = {}
vm.runInNewContext(fs.readFileSync(require.resolve('../cloudfunctions/dataCenter/shared/match-score.cjs'),'utf8'),sandbox)
assert.equal(sandbox.SxfMatchScore.scoreText(match),api.scoreText(match))
assert.deepEqual(api.publicFields({homeScore:3,awayScore:1}),{})
console.log('PASS: PC/H5 score display, public projection, unknown values, winner conflicts and browser module parity')
;(async () => {
  const {calculateMatchEventScore} = await import('../cloudfunctions/dataCenter/shared/match-events.mjs')
  const source=fs.readFileSync(require.resolve('../cloudfunctions/webLoginApi/index.js'),'utf8')
  const finalPublicMap=source.slice(source.indexOf('const matches = Array.from(mergedMatches.values()).map(function (item) {'))
  assert.match(finalPublicMap.slice(0,1000), /return \{ \.\.\.matchScoreView\.publicFields\(item\)/, 'the final public match projection must retain shootout fields')
  const helpers=source.slice(source.indexOf('function publicEventView('),source.indexOf('async function getPublicTournamentCenter()'))
  const scope={}
  vm.runInNewContext(helpers,scope)
  const events=[{type:'goal',teamSide:'home',minute:36},{type:'goal',teamSide:'away',minute:40}]
  const scores=scope.publicScoreFromEvents(events,{},calculateMatchEventScore)
  assert.deepEqual([scores.home,scores.away],[1,1])
  const normalized=events.map(event=>scope.publicEventView(event,match))
  const normalizedScores=scope.publicScoreFromEvents(normalized,undefined,calculateMatchEventScore)
  assert.deepEqual([normalizedScores.home,normalizedScores.away],[1,1])
  const shootout=scope.publicEventView({type:'goal',teamSide:'home',isShootout:true},match)
  const regular=scope.publicScoreFromEvents([...normalized,shootout],{},calculateMatchEventScore)
  assert.deepEqual([regular.home,regular.away],[1,1])
  assert.equal(scope.publicScoreFromEvents([{type:'goal'}],{},calculateMatchEventScore),null)
  console.log('PASS: public H5 score calculation keeps explicit sides, excludes shootouts and preserves unknown identity')
})().catch(error=>{console.error(error);process.exitCode=1})
