const assert = require('node:assert/strict')
const { chromium } = require(process.env.SXF_PLAYWRIGHT_MODULE)

;(async () => {
  const browser = await chromium.launch({ headless:true, executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
  const page = await browser.newPage({ viewport:{ width:1515, height:1080 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('https://**/*', route => route.abort())
  await page.goto('http://127.0.0.1:5197/admin/#/tournaments/qa-tournament-2026/teams/qa-team-zhengzhou?divisionId=qa-division-u16&from=teams&mode=professional&visualQa=1')
  const panel = page.locator('.synthetic-player-panel').filter({ has:page.getByRole('heading', { name:'球员参赛数据' }) }).first()
  const table = panel.locator('.synthetic-player-table')
  await table.locator('.el-table__body-wrapper tbody tr').first().waitFor()
  const headerHeights = await table.locator('th.is-sortable .cell').evaluateAll(cells => cells.map(cell => Math.round(cell.getBoundingClientRect().height)))
  assert.ok(headerHeights.length >= 9 && headerHeights.every(height => height <= 24), `sort headers wrapped: ${headerHeights}`)
  const readNumbers = () => table.locator('.el-table__body-wrapper tbody tr').evaluateAll(rows => rows.map(row => Number(row.querySelectorAll('td')[4]?.textContent.trim())).filter(Number.isFinite))
  const header = table.locator('th').filter({ hasText:'球衣号码' }).first()
  await header.click()
  const ascending = await readNumbers()
  assert.deepEqual(ascending, ascending.slice().sort((a,b) => a-b))
  await header.click()
  const descending = await readNumbers()
  assert.deepEqual(descending, descending.slice().sort((a,b) => b-a))
  await table.locator('th').filter({ hasText:'进球' }).first().click()
  const goals = await table.locator('.el-table__body-wrapper tbody tr').evaluateAll(rows => rows.map(row => Number(row.querySelectorAll('td')[9]?.textContent.trim())).filter(Number.isFinite))
  assert.deepEqual(goals, goals.slice().sort((a,b) => b-a))
  for (const label of ['姓名','球衣名','身份','位置','年龄','出场场次','出场时间','黄牌','红牌']) {
    const column = table.locator('th').filter({ hasText:label }).first()
    await column.click()
    assert.match(await column.getAttribute('class'), /ascending|descending/, `${label} did not sort`)
  }
  const width = await table.evaluate(element => ({ visible:element.clientWidth, content:element.querySelector('.el-table__body-wrapper')?.scrollWidth || 0 }))
  await panel.screenshot({ path:'qa-team-player-sort.png' })
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ rows:descending.length, numberAscending:ascending.slice(0,3), numberDescending:descending.slice(0,3), leadingGoals:goals.slice(0,3), width, errors }))
  await browser.close()
})().catch(error => { console.error(error); process.exitCode=1 })
