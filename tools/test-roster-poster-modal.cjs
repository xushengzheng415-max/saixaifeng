const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium } = require(process.env.SXF_PLAYWRIGHT_MODULE)

;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
  const page = await browser.newPage({ viewport: { width: 1515, height: 1155 }, acceptDownloads: true })
  const pageErrors = []
  let newPages = 0
  page.on('pageerror', error => pageErrors.push(error.message))
  page.on('popup', () => newPages++)
  await page.route('https://**/*', route => route.abort())
  await page.goto('http://127.0.0.1:5197/admin/#/tournaments/qa-tournament-2026/teams/qa-team-zhengzhou?divisionId=qa-division-u16&from=teams&mode=professional&visualQa=1')
  await page.getByRole('button', { name: '球队名单海报' }).click()
  const modal = page.locator('.roster-poster-dialog')
  await modal.waitFor()
  const canvas = modal.locator('.roster-poster-canvas')
  await canvas.locator('.roster-poster-player').first().waitFor()
  const crestStyle = await canvas.locator('.roster-poster-team img, .roster-poster-team-fallback').first().evaluate(element => {
    const style = getComputedStyle(element)
    return { border:style.borderTopWidth, radius:style.borderTopLeftRadius, background:style.backgroundColor }
  })
  assert.equal(crestStyle.border, '0px')
  assert.equal(crestStyle.radius, '0px')
  assert.equal(crestStyle.background, 'rgba(0, 0, 0, 0)')
  assert.equal(await canvas.locator('.roster-poster-player').count(), 22)
  assert.ok((await canvas.innerText()).includes('2026河南青少年足球冠军联赛'))
  assert.ok((await canvas.innerText()).includes('本海报数据由赛小蜂足球提供'))
  assert.equal(newPages, 0)
  await modal.getByRole('button', { name: '红色' }).click()
  assert.ok((await canvas.getAttribute('class')).includes('roster-poster-red'))
  assert.equal(await canvas.locator('.roster-poster-red-player').count(), 22)
  assert.ok((await canvas.innerText()).includes('一线队球员'))
  assert.ok(!(await canvas.innerText()).includes('其他球员'))
  assert.ok(await canvas.locator('.roster-poster-red-player').evaluateAll(cards => cards.every(card => {
    const number = card.querySelector('b')
    const name = card.querySelector('.roster-poster-red-copy')
    return number.scrollHeight <= 80 && number.getBoundingClientRect().bottom < name.getBoundingClientRect().top
  })))
  const redDownloadPromise = page.waitForEvent('download', { timeout: 45000 })
  await modal.getByRole('button', { name: '下载PNG' }).click()
  await (await redDownloadPromise).saveAs('qa-roster-poster-red-downloaded.png')
  await modal.getByRole('button', { name: '蓝色' }).click()
  assert.ok((await canvas.getAttribute('class')).includes('roster-poster-blue'))
  await page.screenshot({ path: 'qa-roster-poster-modal.png' })
  await canvas.screenshot({ path: 'qa-roster-poster-blue.png' })
  await modal.getByRole('button', { name: '绿色' }).click()
  assert.ok((await canvas.getAttribute('class')).includes('roster-poster-green'))
  const downloadPromise = page.waitForEvent('download', { timeout: 45000 })
  await modal.getByRole('button', { name: '下载PNG' }).click()
  const download = await downloadPromise
  await download.saveAs('qa-roster-poster-downloaded.png')
  const bytes = fs.readFileSync('qa-roster-poster-downloaded.png')
  assert.equal(bytes.subarray(1, 4).toString('ascii'), 'PNG')
  assert.ok(bytes.readUInt32BE(16) >= 1200)
  assert.ok(bytes.readUInt32BE(20) >= 2000)
  await page.evaluate(() => { window.print = () => { window.__qaPrintCalled = true } })
  await modal.getByRole('button', { name: '打印' }).click()
  assert.equal(await page.evaluate(() => window.__qaPrintCalled), true)
  await page.setViewportSize({ width: 720, height: 900 })
  assert.ok(await modal.evaluate(element => element.getBoundingClientRect().right <= window.innerWidth + 1))
  assert.ok(await modal.locator('.roster-poster-scroll').evaluate(element => element.clientWidth < 720))
  assert.deepEqual(pageErrors, [])
  console.log(JSON.stringify({ roster: 22, palettes: 3, download: `${bytes.readUInt32BE(16)}x${bytes.readUInt32BE(20)}`, newPages, errors: pageErrors }))
  await browser.close()
})().catch(error => { console.error(error); process.exitCode = 1 })
