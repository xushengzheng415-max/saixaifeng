const assert = require('node:assert/strict')
const { readRights, writeRights } = require('../cloudfunctions/webLoginApi/staffDbRights.cjs')

assert.deepEqual(writeRights('matches', 'update', { matchTime: '10:00' }), ['event.matches'])
assert.deepEqual(writeRights('matches', 'update', { homeScore: 1 }), ['event.results'])
assert.deepEqual(writeRights('matches', 'update', { homeScore: 1, matchTime: '10:00' }), ['event.results', 'event.matches'])
assert.deepEqual(writeRights('matches', 'update', { refereeCrew: {} }), ['event.referees'])
assert.deepEqual(writeRights('divisions', 'update', { name: 'U12' }), ['event.competition'])
assert.deepEqual(writeRights('divisions', 'update', { registrationEnabled: true }), ['event.registration'])
assert.deepEqual(writeRights('tournaments', 'update', { status: 'ongoing' }), ['event.settings'])
assert.deepEqual(writeRights('divisions', 'confirmDivisionRules'), ['event.competition'])
assert.deepEqual(writeRights('tournaments', 'deleteTournamentWorkspace'), ['event.settings'])
assert.deepEqual(writeRights('users', 'update', { role: 'owner' }), [])
assert.deepEqual(readRights('users'), [])
assert.ok(readRights('referees').includes('event.referees'))
console.log('tournament staff DB rights: field-sensitive mapping and deny-by-default passed')
